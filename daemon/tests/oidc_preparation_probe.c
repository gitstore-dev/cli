static int run(gstd_filesystem_input *input, int expected, uint64_t inodes[4]) {
    gstd_filesystem_job job = {0};
    CHECK(!gstd_filesystem_launch(input, 20000, &job));
    gstd_filesystem_reply reply = {.status = -2};
    int done = 0;
    for (unsigned i = 0; i < 25000 && !(done = gstd_filesystem_poll(&job, -1, &reply)); i++)
        usleep(1000);
    if (done != 1 || reply.status != expected)
        fprintf(stderr, "preparation done=%d status=%d expected=%d detail=%d descriptors=%u\n",
                done, reply.status, expected, reply.detail, reply.descriptor_count);
    CHECK(done == 1 && reply.status == expected);
    CHECK(reply.descriptor_count == (expected ? 0u : 4u));
    if (!expected)
        for (size_t i = 0; i < 4; i++) {
            struct stat info;
            int flags = fcntl(reply.descriptors[i], F_GETFL);
            CHECK(flags >= 0 && (flags & O_ACCMODE) == O_RDONLY &&
                  !fstat(reply.descriptors[i], &info) && S_ISREG(info.st_mode) &&
                  info.st_uid == geteuid() && (info.st_mode & 07777) == 0600 &&
                  info.st_nlink == 1 && info.st_size > 0 && info.st_size <= 32768);
            if (inodes)
                inodes[i] = (uint64_t)info.st_ino;
        }
    gstd_filesystem_reply_close(&reply);
    return 0;
}
static int child_directory(int root, const char *name) {
    if (mkdirat(root, name, 0700))
        return -1;
    return openat(root, name, O_RDONLY | O_DIRECTORY | O_CLOEXEC | O_NOFOLLOW);
}
static int only_credential(int directory, char name[256]) {
    int copy = fcntl(directory, F_DUPFD_CLOEXEC, 3);
    if (copy < 3)
        return -1;
    DIR *stream = fdopendir(copy);
    if (!stream) {
        close(copy);
        return -1;
    }
    rewinddir(stream);
    struct dirent *entry;
    unsigned count = 0, locks = 0;
    char lock_name[300] = {0};
    while ((entry = readdir(stream)))
        if (strcmp(entry->d_name, ".") && strcmp(entry->d_name, "..")) {
            if (strlen(entry->d_name) >= 256) {
                closedir(stream);
                return -1;
            }
            if (!strncmp(entry->d_name, ".gs-bootstrap-", 14)) {
                struct stat info;
                if (strlen(entry->d_name) >= sizeof(lock_name) ||
                    fstatat(directory, entry->d_name, &info, AT_SYMLINK_NOFOLLOW) ||
                    !S_ISREG(info.st_mode) || info.st_uid != geteuid() ||
                    (info.st_mode & 07777) != 0600 || info.st_nlink != 1 || info.st_size) {
                    closedir(stream);
                    return -1;
                }
                strcpy(lock_name, entry->d_name);
                locks++;
            } else {
                strcpy(name, entry->d_name);
                count++;
            }
        }
    closedir(stream);
    char expected[300];
    int length =
        count == 1 ? snprintf(expected, sizeof(expected), ".gs-bootstrap-%s.lock", name) : -1;
    return length > 0 && length < (int)sizeof(expected) && locks == 1 &&
                   !strcmp(lock_name, expected)
               ? 0
               : -1;
}
/* Deliberately replace only this fixture's synthetic family. Generated bytes
 * stay in the private child; the control process only renames protected files. */
static int replacement(int root, int directory, const char *name) {
    pid_t parent = getpid(), child = fork();
    CHECK(child >= 0);
    if (!child) {
        struct rlimit core = {0, 0};
        if (setrlimit(RLIMIT_CORE, &core) || prctl(PR_SET_DUMPABLE, 0))
            _exit(1);
        gstd_credential value = {0};
        if (gstd_oidc_material_generate(parent, &value))
            _exit(1);
        unsigned char bytes[1025] = {0};
        int original = openat(root, "retained-credential", O_RDONLY | O_NOFOLLOW | O_CLOEXEC);
        ssize_t length = original >= 3 ? read(original, bytes, sizeof(bytes)) : -1;
        if (original >= 3)
            close(original);
        json_t *prior =
            length > 0 && length <= 1024 ? gstd_json_parse(bytes, (size_t)length) : NULL;
        json_t *fresh = gstd_json_parse(value.bytes, value.length);
        int changed =
            prior && fresh &&
            !json_equal(json_object_get(prior, "clientSecret"),
                        json_object_get(fresh, "clientSecret")) &&
            !json_object_set(prior, "clientSecret", json_object_get(fresh, "clientSecret"));
        char *encoded = changed ? gstd_json_dump(prior) : NULL;
        OPENSSL_cleanse(bytes, sizeof(bytes));
        gstd_oidc_config_clear(prior);
        gstd_oidc_config_clear(fresh);
        json_decref(prior);
        json_decref(fresh);
        gstd_credential_clear(&value);
        if (!encoded)
            _exit(1);
        value.bytes = (unsigned char *)encoded;
        value.length = strlen(encoded);
        if (gstd_oidc_material_check(&value))
            _exit(1);
        int fd =
            openat(directory, name, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0600);
        int valid = fd >= 3 && write(fd, value.bytes, value.length) == (ssize_t)value.length &&
                    !fsync(fd) && !fsync(directory);
        if (fd >= 3)
            close(fd);
        gstd_credential_clear(&value);
        _exit(valid ? 0 : 1);
    }
    int status;
    CHECK(waitpid(child, &status, 0) == child && WIFEXITED(status) && !WEXITSTATUS(status));
    return 0;
}
int main(int argc, char **argv) {
    CHECK((argc == 3 || argc == 5) && argv[1][0] == '/' && argv[2][0] == '/' && geteuid());
    alarm(120);
    gstd_json_initialize();
    int root = open(argv[1], O_RDONLY | O_DIRECTORY | O_CLOEXEC | O_NOFOLLOW),
        broker = open(argv[2], O_RDONLY | O_CLOEXEC | O_NOFOLLOW);
    CHECK(root >= 3 && broker >= 3);
    struct stat info;
    CHECK(!fstat(root, &info) && info.st_uid == geteuid() && (info.st_mode & 07777) == 0700);
    int credentials = child_directory(root, "credentials"), first = child_directory(root, "first"),
        second = child_directory(root, "second"), missing = child_directory(root, "missing");
    CHECK(credentials >= 3 && first >= 3 && second >= 3 && missing >= 3);
    char path[4096];
    CHECK(snprintf(path, sizeof(path), "%s/credentials", argv[1]) > 0);
    gstd_runtime_settings settings = GSTD_RUNTIME_SETTINGS_INITIAL;
    settings.oidc_credential_source =
        json_pack("{s:s,s:s}", "kind", "protected-directory", "path", path);
    settings.oidc_credential_parent_fd = fcntl(credentials, F_DUPFD_CLOEXEC, 3);
    json_t *source = gstd_runtime_settings_oidc_source(
               &settings, "0123456789abcdef0123456789abcdef", "oidc-material-fixture"),
           *selected = json_pack("[s]", "oidc");
#if defined(__aarch64__)
    const char *architecture = "arm64";
#else
    const char *architecture = "amd64";
#endif
    json_t *manifest = selected ? gstd_oidc_core_manifest(selected, architecture, "memdb") : NULL;
    json_decref(selected);
    CHECK(source && manifest);
    gstd_filesystem_input input = {.action = GSTD_FS_OIDC_PREPARE,
                                   .manifest = manifest,
                                   .store_id = "0123456789abcdef0123456789abcdef",
                                   .deployment_id = "oidc-material-fixture",
                                   .operation_id = "first",
                                   .generation = 1,
                                   .descriptors = {first, broker, -1},
                                   .oidc_ports = {24001, 24002, 24003, 24004, 24005},
                                   .credential_source = source};
    CHECK(!run(&input, -1, NULL));
    CHECK(faccessat(first, "owner.json", F_OK, AT_SYMLINK_NOFOLLOW) < 0);
    input.credential_initial = 1;
    uint64_t original[4], repeated[4];
    CHECK(!run(&input, 0, original));
    input.credential_initial = 0;
    CHECK(!run(&input, 0, repeated) && !memcmp(original, repeated, sizeof(original)));
    input.oidc_ports.issuer = 24006;
    CHECK(!run(&input, -1, NULL));
    input.oidc_ports.issuer = 24001;
    CHECK(!run(&input, 0, repeated) && !memcmp(original, repeated, sizeof(original)));
    CHECK(!linkat(first, "hydra/provider.json", first, "hydra/alias", 0));
    CHECK(!run(&input, -1, NULL));
    CHECK(!unlinkat(first, "hydra/alias", 0));
    CHECK(!run(&input, 0, repeated) && !memcmp(original, repeated, sizeof(original)));
    input.credential_prior_required = 1;
    input.descriptors[2] = first;
    input.descriptors[0] = second;
    input.operation_id = "second";
    input.generation = 2;
    CHECK(!run(&input, 0, NULL));
    char credential_name[256];
    CHECK(!only_credential(credentials, credential_name));
    if (argc == 5)
        CHECK(!gstd_test_oidc_async(argv[1], root, first, broker, source, manifest, argv[3],
                                    argv[4]));
    CHECK(!renameat(credentials, credential_name, root, "retained-credential"));
    input.descriptors[0] = missing;
    input.operation_id = "missing";
    input.generation = 3;
    CHECK(!run(&input, -1, NULL));
    CHECK(faccessat(missing, "owner.json", F_OK, AT_SYMLINK_NOFOLLOW) < 0);
    input.descriptors[0] = first;
    input.operation_id = "first";
    input.generation = 1;
    input.credential_initial = 1;
    CHECK(!run(&input, -1, NULL));
    CHECK(!renameat(root, "retained-credential", credentials, credential_name));
    input.credential_initial = 0;
    CHECK(!run(&input, 0, repeated) && !memcmp(original, repeated, sizeof(original)));
    CHECK(!only_credential(credentials, credential_name));
    CHECK(!renameat(credentials, credential_name, root, "retained-credential"));
    CHECK(!replacement(root, credentials, credential_name));
    input.descriptors[0] = missing;
    input.operation_id = "changed-family";
    input.generation = 3;
    CHECK(!run(&input, -1, NULL));
    CHECK(faccessat(missing, "owner.json", F_OK, AT_SYMLINK_NOFOLLOW) < 0);
    CHECK(!unlinkat(credentials, credential_name, 0) &&
          !renameat(root, "retained-credential", credentials, credential_name));
    input.operation_id = "third";
    CHECK(!run(&input, 0, NULL));
    CHECK(!only_credential(credentials, credential_name));
    json_decref(manifest);
    json_decref(source);
    gstd_runtime_settings_clear(&settings);
    close(credentials);
    close(first);
    close(second);
    close(missing);
    close(broker);
    close(root);
    printf("{\"asyncHttpMockVerified\":%s,", argc == 5 ? "true" : "false");
    puts("\"privateConfigDescriptors\":4,\"addOnlyMaterialFamily\":true,\"sameInodesOnReuse\":"
         "true,\"newGenerationReadsExistingMaterial\":true,\"changedPortsRejected\":true,"
         "\"linkedInputRejected\":true,\"missingMaterialNotRegenerated\":true,"
         "\"changedFamilyRejected\":true,\"onlyClientSecretChanged\":true,"
         "\"secretsReadByControlOwner\":false}");
    return 0;
}
